// Runs before `pnpm dev` and `pnpm build`.
// 1) Writes lib/generated/font.ts with ONLY the font chosen in site.config.json
//    (next/font needs a static import, and loading all fonts would waste bytes).
// 2) Copies the mosque logo from assets/ to public/brand/ (if there is one).
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(readFileSync(join(root, "site.config.json"), "utf8"));

const FONTS = {
  Cairo: { fn: "Cairo", subsets: ["arabic", "latin"] },
  Tajawal: { fn: "Tajawal", subsets: ["arabic", "latin"], weight: ["400", "500", "700", "800"] },
  Almarai: { fn: "Almarai", subsets: ["arabic"], weight: ["400", "700", "800"] },
  "Noto Kufi Arabic": { fn: "Noto_Kufi_Arabic", subsets: ["arabic", "latin"] },
  "Readex Pro": { fn: "Readex_Pro", subsets: ["arabic", "latin"] },
  "El Messiri": { fn: "El_Messiri", subsets: ["arabic", "latin", "cyrillic"] },
  Changa: { fn: "Changa", subsets: ["arabic", "latin"] },
  Rubik: { fn: "Rubik", subsets: ["arabic", "latin", "cyrillic"] },
};

const name = config.design?.font ?? "Cairo";
const f = FONTS[name];
if (!f) {
  console.error(`✗ site.config.json → design.font: "${name}" is not available. Choose one of: ${Object.keys(FONTS).join(", ")}`);
  process.exit(1);
}
// next/font needs a plain object literal with unquoted keys (it is analyzed statically).
const literal = (o) =>
  `{ ${Object.entries(o)
    .map(([k, v]) => `${k}: ${JSON.stringify(v)}`)
    .join(", ")} }`;

// Extra fonts for languages whose script the main font doesn't cover (only for languages the mosque enabled).
const locales = config.i18n?.locales ?? ["ar"];
const SCRIPT_FONTS = {
  ur: { fn: "Noto_Nastaliq_Urdu", subsets: ["arabic"], weight: ["400", "700"] },
  hi: { fn: "Noto_Sans_Devanagari", subsets: ["devanagari", "latin"] },
  ru: f.subsets.includes("cyrillic") ? null : { fn: "Noto_Sans", subsets: ["cyrillic", "latin"] },
};
const scripts = Object.entries(SCRIPT_FONTS).filter(([l, v]) => v && locales.includes(l));
const imports = [...new Set([f.fn, ...scripts.map(([, v]) => v.fn)])].join(", ");

mkdirSync(join(root, "lib", "generated"), { recursive: true });
writeFileSync(
  join(root, "lib", "generated", "font.ts"),
  `// Generated by scripts/prepare.mjs from site.config.json — do not edit.\n` +
    `import { ${imports} } from "next/font/google";\n\n` +
    `export const siteFont = ${f.fn}(${literal({ subsets: f.subsets, display: "swap", variable: "--font-site", ...(f.weight ? { weight: f.weight } : {}) })});\n\n` +
    scripts.map(([l, v]) => `const font_${l} = ${v.fn}(${literal({ subsets: v.subsets, display: "swap", variable: "--font-script", ...(v.weight ? { weight: v.weight } : {}) })});\n`).join("") +
    `\n/** Per-language fonts for scripts the main font doesn't cover. */\n` +
    `export const scriptFonts: Record<string, { variable: string } | undefined> = { ${scripts.map(([l]) => `${l}: font_${l}`).join(", ")} };\n`,
);

const brand = join(root, "public", "brand");
rmSync(brand, { recursive: true, force: true });
for (const ext of ["svg", "png"]) {
  const src = join(root, "assets", `logo.${ext}`);
  if (existsSync(src)) {
    mkdirSync(brand, { recursive: true });
    copyFileSync(src, join(brand, `logo.${ext}`));
  }
}
// 3) A tiny TTF subset (only the letters of the mosque name; TTF or WOFF) for the generated icons and share image.
//    Downloaded from Google Fonts at build time; without internet the images just skip the text.
const ttf = join(root, "lib", "generated", "brand-font.bin");
try {
  const text = encodeURIComponent([...new Set(config.name + "مسجد")].join(""));
  const css = await fetch(`https://fonts.googleapis.com/css2?family=${f.fn.replaceAll("_", "+")}:wght@700&text=${text}`, {
    headers: { "User-Agent": "Mozilla/5.0 (Windows NT 6.1) AppleWebKit/534.30 (KHTML, like Gecko) Safari/534.30" },
  }).then((r) => r.text());
  const url = /src:\s*url\(([^)]+)\)\s*format\('(?:truetype|opentype|woff)'\)/.exec(css)?.[1];
  if (url) writeFileSync(ttf, Buffer.from(await fetch(url).then((r) => r.arrayBuffer())));
} catch {
  /* offline: icons fall back to no text */
}

console.log(`✓ prepared: font ${name}${existsSync(brand) ? ", logo from assets/" : ", no logo yet (letter placeholder)"}${existsSync(ttf) ? "" : " (icon font not downloaded)"}`);
